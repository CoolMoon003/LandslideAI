def percentile_to_score(value):
    """
    Convert rainfall amount to trigger score using
    the percentile thresholds already calculated
    in the rainfall dataset.
    """

    if pd.isna(value):
        return np.nan

    if value <= 0:
        return 0.10
    elif value <= 0.25:
        return 0.30
    elif value <= 0.50:
        return 0.50
    elif value <= 0.75:
        return 0.70
    elif value <= 0.90:
        return 0.90
    else:
        return 1.00


def rainfall_trigger_score(row):
    """
    Calculate weighted rainfall trigger.

    We intentionally use the trigger_score columns
    already generated by create_rainfall_features.py.
    """

    scores = [
        row.get("rainfall_1d_score", np.nan),
        row.get("rainfall_3d_score", np.nan),
        row.get("rainfall_7d_score", np.nan),
        row.get("rainfall_15d_score", np.nan),
        row.get("rainfall_30d_score", np.nan),
    ]

    weights = np.array([
        0.15,
        0.15,
        0.30,
        0.20,
        0.20
    ])

    scores = np.array(scores, dtype=float)

    valid = ~np.isnan(scores)

    if not valid.any():
        return np.nan

    weights_valid = weights[valid]
    scores_valid = scores[valid]

    weights_valid = weights_valid / weights_valid.sum()

    return float(np.sum(scores_valid * weights_valid))


def create_rainfall_grid(df):
    """
    Convert the rainfall CSV for the selected date
    into a small regular raster grid.

    Automatically detects latitude/longitude column names.
    """

    print("\nRainfall CSV columns:")
    print(list(df.columns))

    # --------------------------------------------------------
    # Detect latitude column
    # --------------------------------------------------------

    lat_candidates = [
        "lat",
        "latitude",
        "LATITUDE",
        "Latitude"
    ]

    lon_candidates = [
        "lon",
        "longitude",
        "LONGITUDE",
        "Longitude"
    ]

    lat_col = next(
        (col for col in lat_candidates if col in df.columns),
        None
    )

    lon_col = next(
        (col for col in lon_candidates if col in df.columns),
        None
    )

    if lat_col is None or lon_col is None:

        raise ValueError(
            "\nCould not detect latitude/longitude columns.\n"
            f"Available columns: {list(df.columns)}\n"
            "Expected something like lat/lon or latitude/longitude."
        )

    print(
        f"Using latitude column: {lat_col}"
    )

    print(
        f"Using longitude column: {lon_col}"
    )

    # --------------------------------------------------------
    # Get unique coordinates
    # --------------------------------------------------------

    lats = np.sort(
        df[lat_col].astype(float).unique()
    )

    lons = np.sort(
        df[lon_col].astype(float).unique()
    )

    rainfall_grid = np.full(
        (len(lats), len(lons)),
        np.nan,
        dtype=np.float32
    )

    # --------------------------------------------------------
    # Fill rainfall grid
    # --------------------------------------------------------

    lat_lookup = {
        value: idx
        for idx, value in enumerate(lats)
    }

    lon_lookup = {
        value: idx
        for idx, value in enumerate(lons)
    }

    for _, row in df.iterrows():

        lat = float(row[lat_col])
        lon = float(row[lon_col])

        lat_idx = lat_lookup[lat]
        lon_idx = lon_lookup[lon]

        rainfall_grid[
            lat_idx,
            lon_idx
        ] = row["rainfall_trigger"]

    return rainfall_grid, lats, lons
    """
    Convert the rainfall CSV for the selected date
    into a small regular raster grid.

    Rainfall source:
        ~0.25 degree resolution
        5 x 13 Meghalaya cells
    """

    lats = np.sort(df["lat"].unique())
    lons = np.sort(df["lon"].unique())

    rainfall_grid = np.full(
        (len(lats), len(lons)),
        np.nan,
        dtype=np.float32
    )

    for _, row in df.iterrows():

        lat_idx = np.where(lats == row["lat"])[0][0]
        lon_idx = np.where(lons == row["lon"])[0][0]

        rainfall_grid[lat_idx, lon_idx] = row["rainfall_trigger"]

    return rainfall_grid, lats, lons


def reproject_rainfall_to_terrain(
    rainfall_grid,
    lats,
    lons,
    terrain_profile
):
    """
    Efficiently resample the coarse rainfall trigger
    grid onto the 30 m terrain grid.

    Nearest-neighbour is used because rainfall cells are
    categorical/score-based rather than continuous 30 m data.
    """

    source_height, source_width = rainfall_grid.shape

    resolution_x = float(np.median(np.diff(lons)))
    resolution_y = float(np.median(np.diff(lats)))

    # Rainfall coordinates represent cell centers.
    source_transform = from_origin(
        float(lons.min()) - resolution_x / 2,
        float(lats.max()) + resolution_y / 2,
        resolution_x,
        resolution_y
    )

    destination = np.full(
        (
            terrain_profile["height"],
            terrain_profile["width"]
        ),
        np.nan,
        dtype=np.float32
    )

    reproject(
        source=rainfall_grid,
        destination=destination,
        src_transform=source_transform,
        src_crs="EPSG:4326",
        dst_transform=terrain_profile["transform"],
        dst_crs=terrain_profile["crs"],
        resampling=Resampling.nearest,
        src_nodata=np.nan,
        dst_nodata=np.nan
    )

    return destination


def resample_landcover_to_terrain(
    terrain_profile
):
    """
    Resample ESA WorldCover 10 m raster onto
    the 30 m terrain grid.

    Nearest neighbour is mandatory because
    WorldCover classes are categorical.
    """

    print("\n[5] Resampling WorldCover 10 m -> terrain 30 m...")

    destination = np.zeros(
        (
            terrain_profile["height"],
            terrain_profile["width"]
        ),
        dtype=np.float32
    )

    with rasterio.open(LANDCOVER_FILE) as src:

        print("WorldCover dimensions:", (src.height, src.width))
        print("WorldCover CRS:", src.crs)

        reproject(
            source=rasterio.band(src, 1),
            destination=destination,
            src_transform=src.transform,
            src_crs=src.crs,
            dst_transform=terrain_profile["transform"],
            dst_crs=terrain_profile["crs"],
            resampling=Resampling.nearest,
            src_nodata=src.nodata,
            dst_nodata=0
        )

    print("WorldCover successfully aligned to terrain grid.")

    return destination


def save_raster(
    output_file,
    array,
    profile,
    dtype="float32",
    nodata=-9999
):

    output_profile = profile.copy()

    output_profile.update(
        dtype=dtype,
        count=1,
        compress="deflate",
        predictor=2,
        nodata=nodata
    )

    output_array = np.array(array, copy=True)

    if np.issubdtype(np.dtype(dtype), np.floating):

        output_array = np.where(
            np.isfinite(output_array),
            output_array,
            nodata
        )

    with rasterio.open(
        output_file,
        "w",
        **output_profile
    ) as dst:

        dst.write(
            output_array.astype(dtype),
            1
        )


