def main():

    print("=" * 75)
    print("YHACK LANDSLIDE AI - DYNAMIC RISK ENGINE")
    print("=" * 75)

    # --------------------------------------------------------
    # 1. LOAD RAINFALL SCENARIO
    # --------------------------------------------------------

    print("\n[1] Loading rainfall scenario...")

    rainfall_df = pd.read_csv(
        RAINFALL_FILE
    )

    rainfall_df["date"] = pd.to_datetime(
        rainfall_df["date"]
    )

    scenario = rainfall_df[
        rainfall_df["date"] == pd.Timestamp(SCENARIO_DATE)
    ].copy()

    if scenario.empty:
        raise ValueError(
            f"No rainfall data found for {SCENARIO_DATE}"
        )

    print("Scenario date:", SCENARIO_DATE)
    print("Rainfall cells:", len(scenario))

    # --------------------------------------------------------
    # 2. CALCULATE RAINFALL TRIGGER
    # --------------------------------------------------------

    print("\n[2] Calculating rainfall trigger...")

    scenario["rainfall_trigger"] = scenario.apply(
        rainfall_trigger_score,
        axis=1
    )

    print("\nRainfall trigger statistics:")

    print(
        scenario["rainfall_trigger"].describe()
    )

    # --------------------------------------------------------
    # 3. LOAD RANDOM FOREST
    # --------------------------------------------------------

    print("\n[3] Loading Random Forest model...")

    model = joblib.load(
        MODEL_FILE
    )

    print("Model loaded:", MODEL_FILE)

    # --------------------------------------------------------
    # 4. LOAD TERRAIN
    # --------------------------------------------------------

    print("\n[4] Loading terrain features...")

    with rasterio.open(ELEVATION_FILE) as src:

        elevation = src.read(1).astype(np.float32)

        terrain_profile = src.profile.copy()

        terrain_transform = src.transform
        terrain_crs = src.crs

        height = src.height
        width = src.width

    with rasterio.open(SLOPE_FILE) as src:

        slope = src.read(1).astype(np.float32)

        if src.shape != (height, width):
            raise ValueError(
                "Slope raster does not match elevation raster."
            )

    with rasterio.open(ASPECT_FILE) as src:

        aspect = src.read(1).astype(np.float32)

        if src.shape != (height, width):
            raise ValueError(
                "Aspect raster does not match elevation raster."
            )

    with rasterio.open(CURVATURE_FILE) as src:

        curvature = src.read(1).astype(np.float32)

        if src.shape != (height, width):
            raise ValueError(
                "Curvature raster does not match elevation raster."
            )

    print(
        "Terrain dimensions:",
        (height, width)
    )

    print(
        "Terrain CRS:",
        terrain_crs
    )

    # --------------------------------------------------------
    # 5. RESAMPLE LANDCOVER
    # --------------------------------------------------------

    landcover = resample_landcover_to_terrain(
        terrain_profile
    )

    # --------------------------------------------------------
    # 6. BUILD RAINFALL TRIGGER GRID
    # --------------------------------------------------------

    print("\n[6] Creating rainfall trigger raster...")

    rainfall_grid, rainfall_lats, rainfall_lons = (
        create_rainfall_grid(scenario)
    )

    print(
        "Rainfall grid:",
        rainfall_grid.shape
    )

    rainfall_trigger_raster = (
        reproject_rainfall_to_terrain(
            rainfall_grid,
            rainfall_lats,
            rainfall_lons,
            terrain_profile
        )
    )

    valid_rainfall = np.isfinite(
        rainfall_trigger_raster
    )

    print(
        "Terrain pixels receiving rainfall data:",
        int(valid_rainfall.sum())
    )

    # --------------------------------------------------------
    # 7. RANDOM FOREST SUSCEPTIBILITY
    # --------------------------------------------------------

    print("\n[7] Predicting landslide susceptibility...")

    total_pixels = height * width

    print(
        "Total terrain pixels:",
        f"{total_pixels:,}"
    )

    susceptibility = np.full(
        (height, width),
        np.nan,
        dtype=np.float32
    )

    # Valid pixels

    valid_mask = (
        np.isfinite(elevation)
        &
        np.isfinite(slope)
        &
        np.isfinite(aspect)
        &
        np.isfinite(curvature)
        &
        (landcover > 0)
    )

    valid_mask &= valid_rainfall

    valid_indices = np.flatnonzero(
        valid_mask.ravel()
    )

    print(
        "Valid prediction pixels:",
        f"{len(valid_indices):,}"
    )

    # --------------------------------------------------------
    # PREDICT IN CHUNKS
    # --------------------------------------------------------

    CHUNK_SIZE = 500_000

    flat_elevation = elevation.ravel()
    flat_slope = slope.ravel()
    flat_aspect = aspect.ravel()
    flat_curvature = curvature.ravel()
    flat_landcover = landcover.ravel()

    susceptibility_flat = susceptibility.ravel()

    for start in range(
        0,
        len(valid_indices),
        CHUNK_SIZE
    ):

        end = min(
            start + CHUNK_SIZE,
            len(valid_indices)
        )

        idx = valid_indices[start:end]

        X = np.column_stack([
            flat_elevation[idx],
            flat_slope[idx],
            flat_aspect[idx],
            flat_curvature[idx],
            flat_landcover[idx]
        ])

        probabilities = model.predict_proba(
            X
        )[:, 1]

        susceptibility_flat[idx] = (
            probabilities.astype(np.float32)
        )

        print(
            f"  Predicted {end:,} / "
            f"{len(valid_indices):,} pixels"
        )

    susceptibility = susceptibility_flat.reshape(
        height,
        width
    )

    print(
        "\nSusceptibility statistics:"
    )

    valid_susc = susceptibility[
        np.isfinite(susceptibility)
    ]

    print(
        pd.Series(valid_susc).describe()
    )

    # --------------------------------------------------------
    # 8. DYNAMIC RISK
    # --------------------------------------------------------

    print("\n[8] Calculating dynamic risk...")

    dynamic_risk = (
        susceptibility
        *
        rainfall_trigger_raster
    )

    dynamic_risk[
        ~np.isfinite(dynamic_risk)
    ] = np.nan

    valid_risk = dynamic_risk[
        np.isfinite(dynamic_risk)
    ]

    print(
        "\nDynamic risk statistics:"
    )

    print(
        pd.Series(valid_risk).describe()
    )

    # --------------------------------------------------------
    # 9. RISK CATEGORIES
    # --------------------------------------------------------

    print("\n[9] Creating risk categories...")

    risk_class = np.zeros(
        (height, width),
        dtype=np.uint8
    )

    valid = np.isfinite(
        dynamic_risk
    )

    # These are presentation thresholds for the MVP.
    # They are NOT scientific universal thresholds.

    risk_class[
        valid & (dynamic_risk < 0.20)
    ] = 1

    risk_class[
        valid
        & (dynamic_risk >= 0.20)
        & (dynamic_risk < 0.35)
    ] = 2

    risk_class[
        valid
        & (dynamic_risk >= 0.35)
        & (dynamic_risk < 0.50)
    ] = 3

    risk_class[
        valid
        & (dynamic_risk >= 0.50)
        & (dynamic_risk < 0.65)
    ] = 4

    risk_class[
        valid
        & (dynamic_risk >= 0.65)
        & (dynamic_risk < 0.80)
    ] = 5

    risk_class[
        valid & (dynamic_risk >= 0.80)
    ] = 6

    class_names = {
        1: "LOW",
        2: "MODERATE",
        3: "ELEVATED",
        4: "HIGH",
        5: "VERY HIGH",
        6: "EXTREME"
    }

    print("\nRisk distribution:")

    for class_id, name in class_names.items():

        count = int(
            np.sum(
                risk_class == class_id
            )
        )

        percentage = (
            count / max(int(valid.sum()), 1)
        ) * 100

        print(
            f"{name:12s}: "
            f"{count:,} pixels "
            f"({percentage:.2f}%)"
        )

    # --------------------------------------------------------
    # 10. SAVE OUTPUTS
    # --------------------------------------------------------

    print("\n[10] Saving output rasters...")

    susceptibility_file = os.path.join(
        OUTPUT_DIR,
        "susceptibility_30m.tif"
    )

    rainfall_file = os.path.join(
        OUTPUT_DIR,
        f"rainfall_trigger_{SCENARIO_DATE}.tif"
    )

    dynamic_file = os.path.join(
        OUTPUT_DIR,
        f"dynamic_risk_{SCENARIO_DATE}.tif"
    )

    risk_class_file = os.path.join(
        OUTPUT_DIR,
        f"risk_class_{SCENARIO_DATE}.tif"
    )

    save_raster(
        susceptibility_file,
        susceptibility,
        terrain_profile
    )

    save_raster(
        rainfall_file,
        rainfall_trigger_raster,
        terrain_profile
    )

    save_raster(
        dynamic_file,
        dynamic_risk,
        terrain_profile
    )

    save_raster(
        risk_class_file,
        risk_class,
        terrain_profile,
        dtype="uint8",
        nodata=0
    )

    # --------------------------------------------------------
    # FINISH
    # --------------------------------------------------------

    print("\n" + "=" * 75)
    print("DYNAMIC RISK ENGINE COMPLETE")
    print("=" * 75)

    print("\nCreated:")

    print(
        "1.",
        susceptibility_file
    )

    print(
        "2.",
        rainfall_file
    )

    print(
        "3.",
        dynamic_file
    )

    print(
        "4.",
        risk_class_file
    )

    print("\nScenario:", SCENARIO_DATE)

    print(
        "\nIMPORTANT:"
        "\nRainfall is based on the available ~0.25° rainfall grid."
        "\nIt is NOT 30 m rainfall."
        "\nThe 30 m raster is only the output/display grid."
    )


if __name__ == "__main__":
    main()